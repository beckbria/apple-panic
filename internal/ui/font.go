// FontRenderer caches white 8x8 glyph images and draws crisp scaled bitmap text.
type FontRenderer struct {
	glyphs [96]*ebiten.Image
}

func NewFontRenderer() *FontRenderer {
	fr := &FontRenderer{}
	for idx := 0; idx < 96; idx++ {
		im := image.NewNRGBA(image.Rect(0, 0, 8, 8))
		rows := font8x8[idx]
		for y := 0; y < 8; y++ {
			row := rows[y]
			for x := 0; x < 8; x++ {
				if (row>>(7-x))&1 != 0 {
					im.SetNRGBA(x, y, color.NRGBA{R: 255, G: 255, B: 255, A: 255})
				}
			}
		}
		fr.glyphs[idx] = ebiten.NewImageFromImage(im)
	}
	return fr
}

// Draw draws text at pixel coordinates (x, y) on dst at integer or float scale.
func (fr *FontRenderer) Draw(dst *ebiten.Image, text string, x, y, scale float64, clr color.Color) {
	r, g, b, a := clr.RGBA()
	rf := float32(r) / 65535.0
	gf := float32(g) / 65535.0
	bf := float32(b) / 65535.0
	af := float32(a) / 65535.0

	cx := x
	for _, ch := range text {
		if ch == '\n' {
			cx = x
			y += 10 * scale
			continue
		}
		idx := int(ch) - 32
		if idx < 0 || idx >= 96 {
			idx = '?' - 32
		}
		if idx > 0 {
			var op ebiten.DrawImageOptions
			op.GeoM.Scale(scale, scale)
			op.GeoM.Translate(cx, y)
			op.ColorScale.Scale(rf, gf, bf, af)
			dst.DrawImage(fr.glyphs[idx], &op)
		}
		cx += 8 * scale
	}
}

// DrawShadowed draws text with a 1-unit black drop shadow for high contrast over graphics.
func (fr *FontRenderer) DrawShadowed(dst *ebiten.Image, text string, x, y, scale float64, clr color.Color) {
	fr.Draw(dst, text, x+scale, y+scale, scale, color.NRGBA{R: 0, G: 0, B: 0, A: 220})
	fr.Draw(dst, text, x, y, scale, clr)
}

// DrawCentered draws text horizontally centered around centerX.
func (fr *FontRenderer) DrawCentered(dst *ebiten.Image, text string, centerX, y, scale float64, clr color.Color) {
	w := float64(len(text)) * 8.0 * scale
	fr.DrawShadowed(dst, text, centerX-w/2.0, y, scale, clr)
}
